func credentials(as Asset, roots ...string) (map[string]string, error) {
	ref := str(as.Settings["credentialRef"])
	if ref == "" {
		return map[string]string{}, nil
	}
	path, err := privateCredential(ref, roots...)
	if err != nil {
		return nil, err
	}
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, errors.New("credential file unavailable")
	}
	var m map[string]string
	if json.Unmarshal(b, &m) != nil {
		return nil, errors.New("credential must be a JSON object")
	}
	return m, nil
}
func databaseOpen(as Asset, readonly bool, dbname string, roots ...string) (*sql.DB, string, error) {
	if as.Kind != "database" {
		return nil, "", errors.New("not a database asset")
	}
	creds, err := credentials(as, roots...)
	if err != nil {
		return nil, "", err
	}
	driver := str(as.Settings["driver"])
	dsn := ""
	db := str(as.Settings["database"])
	if dbname != "" {
		db = dbname
	}
	host := str(as.Settings["host"])
	if driver != "sqlite" && !hostPattern.MatchString(host) {
		return nil, "", errors.New("database host must be explicitly configured")
	}
	user := creds["username"]
	if user == "" {
		user = str(as.Settings["username"])
	}
	switch driver {
	case "postgres", "postgresql":
		driver = "pgx"
		u := url.URL{Scheme: "postgres", Host: net.JoinHostPort(host, fmt.Sprint(num(as.Settings["port"], 5432))), Path: "/" + db, User: url.UserPassword(user, creds["password"])}
		q := u.Query()
		sslmode := str(as.Settings["sslmode"])
		if sslmode == "" {
			sslmode = "verify-full"
		}
		q.Set("sslmode", sslmode)
		u.RawQuery = q.Encode()
		dsn = u.String()
	case "mysql":
		conf := mysql.NewConfig()
		conf.User = user
		conf.Passwd = creds["password"]
		conf.Net = "tcp"
		conf.Addr = net.JoinHostPort(host, fmt.Sprint(num(as.Settings["port"], 3306)))
		conf.DBName = db
		conf.ParseTime = true
		conf.Timeout = 10 * time.Second
		conf.TLSConfig = "true"
		if as.Settings["tls"] == false {
			conf.TLSConfig = "false"
		}
		dsn = conf.FormatDSN()
	case "sqlite":
		driver = "sqlite3"
		path := str(as.Settings["path"])
		if err = safeFile(path); err != nil {
			return nil, "", err
		}
		if real, e := filepath.EvalSymlinks(path); e == nil {
			if err = safeFile(real); err != nil {
				return nil, "", err
			}
		}
		u := url.URL{Scheme: "file", Path: path}
		q := u.Query()
		q.Set("mode", "rw")
		if readonly {
			q.Set("mode", "ro")
		}
		q.Set("_busy_timeout", "5000")
		u.RawQuery = q.Encode()
		dsn = u.String()
	default:
		return nil, "", errors.New("database driver must be postgres, mysql or sqlite")
	}
	conn, err := sql.Open(driver, dsn)
	if err != nil {
		return nil, "", errors.New("database connection configuration invalid")
	}
	conn.SetMaxOpenConns(1)
	return conn, driver, nil
}
func tableQuery(driver, name string, a map[string]any) (string, []any, error) {
	schema := str(a["schema"])
	table := str(a["table"])
	category := str(a["query_type"])
	if category == "" {
		category = "table"
	}
	if name == "db_table_ddl" {
		switch driver {
		case "sqlite3":
			return "SELECT sql FROM sqlite_master WHERE name = ?", []any{table}, nil
		case "mysql":
			if schema == "" || table == "" {
				return "", nil, errors.New("schema and table required")
			}
			return "SHOW CREATE TABLE `" + strings.ReplaceAll(schema, "`", "``") + "`.`" + strings.ReplaceAll(table, "`", "``") + "`", nil, nil
		case "pgx":
			return `SELECT 'CREATE TABLE ' || quote_ident(n.nspname) || '.' || quote_ident(c.relname) || E' (\n' ||
(SELECT string_agg('  ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid,a.atttypmod) ||
CASE WHEN a.attidentity='a' THEN ' GENERATED ALWAYS AS IDENTITY' WHEN a.attidentity='d' THEN ' GENERATED BY DEFAULT AS IDENTITY'
WHEN a.attgenerated='s' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(d.adbin,d.adrelid) || ') STORED'
ELSE COALESCE(' DEFAULT ' || pg_get_expr(d.adbin,d.adrelid),'') END || CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END,
E',\n' ORDER BY a.attnum) FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum WHERE a.attrelid=c.oid AND a.attnum>0 AND NOT a.attisdropped) ||
COALESCE((SELECT E',\n' || string_agg('  CONSTRAINT ' || quote_ident(conname) || ' ' || pg_get_constraintdef(oid,true),E',\n') FROM pg_constraint WHERE conrelid=c.oid),'') || E'\n);' ||
COALESCE((SELECT E'\n' || string_agg(pg_get_indexdef(i.indexrelid) || ';',E'\n') FROM pg_index i WHERE i.indrelid=c.oid AND NOT EXISTS (SELECT 1 FROM pg_constraint q WHERE q.conindid=i.indexrelid)),'') AS ddl
FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname=$1 AND c.relname=$2`, []any{schema, table}, nil
		}
	}
	if driver == "sqlite3" {
		if category == "database" || category == "schema" {
			return "PRAGMA database_list", nil, nil
		}
		return "SELECT name,type FROM sqlite_master WHERE type IN ('table','view','index','trigger') ORDER BY name", nil, nil
	}
	if driver == "pgx" {
		switch category {
		case "database":
			return "SELECT datname AS name,'database' AS type FROM pg_database WHERE datallowconn", nil, nil
		case "schema":
			return "SELECT schema_name AS name,'schema' AS type FROM information_schema.schemata", nil, nil
		case "function", "procedure":
			return "SELECT routine_name AS name,routine_type AS type FROM information_schema.routines WHERE routine_schema=$1", []any{schema}, nil
		default:
			return "SELECT table_name AS name,table_type AS type FROM information_schema.tables WHERE table_schema=$1 ORDER BY table_name", []any{schema}, nil
		}
	}
	if category == "database" || category == "schema" {
		return "SELECT schema_name AS name,'schema' AS type FROM information_schema.schemata", nil, nil
	}
	if category == "function" || category == "procedure" {
		return "SELECT routine_name AS name,routine_type AS type FROM information_schema.routines WHERE routine_schema=?", []any{schema}, nil
	}
	return "SELECT table_name AS name,table_type AS type FROM information_schema.tables WHERE table_schema=? ORDER BY table_name", []any{schema}, nil
}
func (e *Engine) database(ctx context.Context, c Config, name string, a map[string]any) (any, error) {
	as, err := asset(c, str(a["asset_ref"]))
	if err != nil {
		return nil, err
	}
	readonly := name != "execute_sql" || readonlySQL(str(a["sql"]))
	db, driver, err := databaseOpen(as, readonly, str(a["db"]), c.CredentialDir)
	if err != nil {
		return nil, err
	}
	defer db.Close()
	ctx, cancel := context.WithTimeout(ctx, duration(a))
	defer cancel()
	tx, err := db.BeginTx(ctx, &sql.TxOptions{ReadOnly: readonly})
	if err != nil {
		return nil, errors.New("database connection or transaction failed")
	}
	defer tx.Rollback()
	if driver == "sqlite3" && readonly {
		if _, err = tx.ExecContext(ctx, "PRAGMA query_only=ON"); err != nil {
			return nil, errors.New("cannot enforce SQLite read-only mode")
		}
	}
	query := str(a["sql"])
	params := []any{}
	if name != "execute_sql" {
		query, params, err = tableQuery(driver, name, a)
		if err != nil {
			return nil, err
		}
	}
	if !readonly {
		r, err := tx.ExecContext(ctx, query)
		if err != nil {
			return nil, errors.New("SQL execution failed")
		}
		affected, _ := r.RowsAffected()
		if err = tx.Commit(); err != nil {
			return nil, errors.New("SQL commit failed; inspect outcome")
		}
		return map[string]any{"affected_rows": affected}, nil
	}
	rows, err := tx.QueryContext(ctx, query, params...)
	if err != nil {
		return nil, errors.New("SQL query failed")
	}
	defer rows.Close()
	columns, err := rows.Columns()
	if err != nil {
		return nil, errors.New("cannot read SQL columns")
	}
	values := []any{}
	size := 0
	truncated := false
	pattern, err := regexp.Compile("(?i)" + str(a["pattern"]))
	if err != nil {
		return nil, errors.New("invalid object filter")
	}
	for rows.Next() {
		row := make([]any, len(columns))
		pointers := make([]any, len(columns))
		for i := range row {
			pointers[i] = &row[i]
		}
		if rows.Scan(pointers...) != nil {
			return nil, errors.New("cannot read SQL row")
		}
		entry := map[string]any{}
		for i, key := range columns {
			v := row[i]
			if b, ok := v.([]byte); ok {
				v = string(b)
			}
			entry[key] = v
		}
		encoded := js(entry)
		if name == "list_db_objects" && !pattern.MatchString(encoded) {
			continue
		}
		size += len(encoded)
		if len(values) >= 1000 || size > 100000 {
			truncated = true
			break
		}
		values = append(values, entry)
	}
	if err = rows.Err(); err != nil {
		return nil, errors.New("SQL row stream failed")
	}
	return map[string]any{"columns": columns, "rows": values, "truncated": truncated}, nil
}
func respWrite(w io.Writer, parts []string) error {
	var b strings.Builder
	fmt.Fprintf(&b, "*%d\r\n", len(parts))
	for _, p := range parts {
		fmt.Fprintf(&b, "$%d\r\n%s\r\n", len(p), p)
	}
	_, err := io.WriteString(w, b.String())
	return err
}
func respRead(r *bufio.Reader, depth int) (any, error) {
	if depth > 20 {
		return nil, errors.New("Redis response nesting limit")
	}
	line, err := r.ReadString('\n')
	if err != nil || len(line) < 3 || len(line) > 100000 {
		return nil, errors.New("invalid Redis response")
	}
	text := strings.TrimSuffix(strings.TrimSuffix(line, "\n"), "\r")
	switch text[0] {
	case '+':
		return text[1:], nil
	case '-':
		return nil, errors.New("Redis returned an error")
	case ':':
		return strconv.ParseInt(text[1:], 10, 64)
	case '$':
		n, err := strconv.Atoi(text[1:])
		if err != nil || n < -1 || n > 100000 {
			return nil, errors.New("Redis bulk response limit")
		}
		if n == -1 {
			return nil, nil
		}
		b := make([]byte, n+2)
		_, err = io.ReadFull(r, b)
		if err != nil {
			return nil, err
		}
		return string(b[:n]), nil
	case '*':
		n, err := strconv.Atoi(text[1:])
		if err != nil || n < -1 || n > 1000 {
			return nil, errors.New("Redis array limit")
		}
		if n == -1 {
			return nil, nil
		}
		a := []any{}
		for i := 0; i < n; i++ {
			v, err := respRead(r, depth+1)
			if err != nil {
				return nil, err
			}
			a = append(a, v)
		}
		return a, nil
	}
	return nil, errors.New("unsupported Redis response")
}
func (e *Engine) redis(ctx context.Context, c Config, a map[string]any) (any, error) {
	as, err := asset(c, str(a["asset_ref"]))
	if err != nil || as.Kind != "redis" {
		return nil, errors.New("Redis asset required")
	}
	if !hostPattern.MatchString(str(as.Settings["host"])) {
		return nil, errors.New("Redis host must be explicitly configured")
	}
	creds, err := credentials(as, c.CredentialDir)
	if err != nil {
		return nil, err
	}
	parts, err := words(str(a["command"]))
	if err != nil || len(parts) == 0 {
		return nil, errors.New("invalid Redis command")
	}
	ctx, cancel := context.WithTimeout(ctx, duration(a))
	defer cancel()
	address := net.JoinHostPort(str(as.Settings["host"]), fmt.Sprint(num(as.Settings["port"], 6379)))
	dialer := net.Dialer{Timeout: 10 * time.Second}
	var conn net.Conn
	if as.Settings["tls"] == true {
		td := tls.Dialer{NetDialer: &dialer, Config: &tls.Config{MinVersion: tls.VersionTLS12, ServerName: str(as.Settings["host"])}}
		conn, err = td.DialContext(ctx, "tcp", address)
	} else {
		conn, err = dialer.DialContext(ctx, "tcp", address)
	}
	if err != nil {
		return nil, errors.New("Redis connection failed")
	}
	defer conn.Close()
	deadline, _ := ctx.Deadline()
	_ = conn.SetDeadline(deadline)
	stop := context.AfterFunc(ctx, func() { conn.Close() })
	defer stop()
	r := bufio.NewReader(io.LimitReader(conn, 200000))
	send := func(parts []string) (any, error) {
		if err := respWrite(conn, parts); err != nil {
			return nil, errors.New("Redis send failed")
		}
		return respRead(r, 0)
	}
	if creds["password"] != "" {
		auth := []string{"AUTH"}
		if creds["username"] != "" {
			auth = append(auth, creds["username"])
		}
		auth = append(auth, creds["password"])
		if _, err = send(auth); err != nil {
			return nil, errors.New("Redis authentication failed")
		}
	}
	db := num(a["db"], num(as.Settings["db"], 0))
	if db < 0 || db > 65535 {
		return nil, errors.New("invalid Redis database")
	}
	if db != 0 {
		if _, err = send([]string{"SELECT", fmt.Sprint(db)}); err != nil {
			return nil, err
		}
	}
	return send(parts)
}
func (e *Engine) web(ctx context.Context, name string, a map[string]any) (any, error) {
	endpoint := str(a["url"])
	if name == "web_search" {
		endpoint = "https://html.duckduckgo.com/html/?q=" + url.QueryEscape(str(a["query"]))
	}
	u, err := url.Parse(endpoint)
	if err != nil || (u.Scheme != "http" && u.Scheme != "https") || u.User != nil {
		return nil, errors.New("invalid web URL")
	}
	ctx, cancel := context.WithTimeout(ctx, 30*time.Second)
	defer cancel()
	request, _ := http.NewRequestWithContext(ctx, "GET", endpoint, nil)
	request.Header.Set("User-Agent", "Lake/0.1")
	response, err := HTTPClient.Do(request)
	if err != nil {
		return nil, errors.New("web request failed")
	}
	defer response.Body.Close()
	b, err := io.ReadAll(io.LimitReader(response.Body, 100001))
	if err != nil {
		return nil, errors.New("web read failed")
	}
	return map[string]any{"url": endpoint, "status": response.StatusCode, "content": string(b[:min(len(b), 100000)]), "truncated": len(b) > 100000}, nil
}
func (e *Engine) transfer(ctx context.Context, id string, c Config, name string, a map[string]any) (any, error) {
	if name == "close_ssh_tunnel" {
		key := id + ":" + str(a["tunnel_id"])
		v, ok := e.tunnels.LoadAndDelete(key)
		if !ok {
			return nil, errors.New("tunnel unavailable in this session")
		}
		v.(context.CancelFunc)()
		return map[string]any{"closed": true}, nil
	}
	as, err := asset(c, str(a["asset_ref"]))
	if err != nil || as.Kind != "ssh" {
		return nil, errors.New("SSH asset required")
	}
	base, err := sshBase(as.SSH, c.CredentialDir)
	if err != nil {
		return nil, err
	}
	env, err := sshEnvironment(as.SSH, c.CredentialDir)
	if err != nil {
		return nil, err
	}
	if name == "scp_transfer" {
		local := str(a["local_path"])
		remote := str(a["remote_path"])
		if err = safeLocalFile(local); err != nil {
			return nil, err
		}
		if err = safeFile(remote); err != nil {
			return nil, err
		}
		direction := str(a["direction"])
		if direction != "upload" && direction != "download" {
			return nil, errors.New("invalid transfer direction")
		}
		if a["overwrite"] != true {
			if direction == "download" {
				if _, err = os.Stat(local); err == nil {
					return nil, errors.New("destination exists; explicit overwrite required")
				}
			} else {
				r, err := e.execRuntime(ctx, c, map[string]any{"runtime": "ssh", "asset_ref": as.ID}, []string{"test", "-e", remote}, "")
				if err != nil {
					return nil, err
				}
				if num(r["exitCode"], 0) == 0 {
					return nil, errors.New("destination exists; explicit overwrite required")
				}
			}
		}
		remoteArg := as.SSH.Username + "@" + as.SSH.Host + ":" + remote
		cmdargs := append(base, "-P", fmt.Sprint(as.SSH.Port))
		if direction == "upload" {
			cmdargs = append(cmdargs, "--", local, remoteArg)
		} else {
			cmdargs = append(cmdargs, "--", remoteArg, local)
		}
		ctx, cancel := context.WithTimeout(ctx, duration(a))
		defer cancel()
		cmd := exec.CommandContext(ctx, "scp", cmdargs...)
		cmd.Env = env
		setupProcess(cmd)
		if cmd.Run() != nil {
			return nil, errors.New("SCP transfer failed; inspect destination before retrying")
		}
		return map[string]any{"transferred": true}, nil
	}
	target := str(a["target_host"])
	bind := str(a["bind_host"])
	if bind == "" {
		bind = "127.0.0.1"
	}
	if !hostPattern.MatchString(target) || !hostPattern.MatchString(bind) {
		return nil, errors.New("invalid tunnel hostname")
	}
	targetPort := num(a["target_port"], 0)
	bindPort := num(a["bind_port"], 0)
	if targetPort < 1 || targetPort > 65535 || bindPort < 0 || bindPort > 65535 {
		return nil, errors.New("invalid tunnel port")
	}
	direction := str(a["direction"])
	if direction == "" {
		direction = "local"
	}
	flag := "-L"
	if direction == "remote" {
		flag = "-R"
	} else if direction != "local" {
		return nil, errors.New("invalid tunnel direction")
	}
	if bindPort == 0 {
		if direction == "local" {
			listener, err := net.Listen("tcp", net.JoinHostPort(bind, "0"))
			if err != nil {
				return nil, errors.New("cannot allocate tunnel port")
			}
			bindPort = listener.Addr().(*net.TCPAddr).Port
			listener.Close()
		}
	}
	tunnelID := uid()
	lifetime, cancel := context.WithCancel(context.Background())
	forward := net.JoinHostPort(bind, fmt.Sprint(bindPort)) + ":" + net.JoinHostPort(target, fmt.Sprint(targetPort))
	cmdargs := append(base, "-v", "-N", "-o", "ExitOnForwardFailure=yes", flag, forward, "-p", fmt.Sprint(as.SSH.Port), "-l", as.SSH.Username, as.SSH.Host)
	command := exec.CommandContext(lifetime, "ssh", cmdargs...)
	command.Env = env
	setupProcess(command)
	stderr, err := command.StderrPipe()
	if err != nil {
		cancel()
		return nil, errors.New("cannot observe tunnel startup")
	}
	if err = command.Start(); err != nil {
		cancel()
		return nil, errors.New("SSH tunnel could not start")
	}
	key := id + ":" + tunnelID
	e.tunnels.Store(key, cancel)
	done := make(chan error, 1)
	go func() { done <- command.Wait(); e.tunnels.Delete(key) }()
	ready := make(chan int, 1)
	requestedPort := bindPort
	go func() {
		scanner := bufio.NewScanner(stderr)
		for scanner.Scan() {
			line := scanner.Text()
			port := requestedPort
			if strings.Contains(line, "Allocated port ") {
				parts := strings.Fields(line)
				for i, p := range parts {
					if p == "port" && i+1 < len(parts) {
						port, _ = strconv.Atoi(parts[i+1])
						break
					}
				}
			}
			if direction == "remote" && (strings.Contains(line, "Allocated port ") || strings.Contains(line, "remote forward success")) {
				select {
				case ready <- port:
				default:
				}
			}
		}
	}()
	startup := time.NewTimer(10 * time.Second)
	defer startup.Stop()
	poll := time.NewTicker(50 * time.Millisecond)
	defer poll.Stop()
	for {
		select {
		case <-ctx.Done():
			cancel()
			return nil, ctx.Err()
		case <-done:
			cancel()
			return nil, errors.New("SSH tunnel failed to open")
		case port := <-ready:
			if port > 0 {
				bindPort = port
				goto opened
			}
		case <-startup.C:
			cancel()
			return nil, errors.New("SSH tunnel startup timed out")
		case <-poll.C:
			if direction == "local" {
				host := bind
				if host == "0.0.0.0" {
					host = "127.0.0.1"
				}
				conn, err := net.DialTimeout("tcp", net.JoinHostPort(host, fmt.Sprint(bindPort)), 100*time.Millisecond)
				if err == nil {
					conn.Close()
					goto opened
				}
			}
		}
	}
opened:

	return map[string]any{"tunnel_id": tunnelID, "bind_host": bind, "bind_port": bindPort, "direction": direction}, nil
}
