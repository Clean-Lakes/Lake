test('configuration sources, revisions, project scope, Plan and cancellation are checked before I/O', async (t) => {
    const f = await fixture(t), resource = (await f.resourceList()).items.find((i) => i.entity === 'resource');
    const args = { event_id: f.event.id, part_key: 'stable', quote: f.event.payload, entity: 'resource', action: 'update', id: resource.id, name: '已改名', expected_revision: resource.revision };
    const saved = await f.call('manage_resource', args);
    assert.deepEqual(await f.call('manage_resource', args), saved);
    await assert.rejects(f.call('manage_resource', { ...args, name: '冲突' }), /冲突/);
    await assert.rejects(f.change('manage_resource', { entity: 'resource', action: 'update', id: resource.id, name: '旧版本', expected_revision: resource.revision }), /配置已变化/);
    const other = f.store.createProject('其他项目'), foreign = f.store.catalog().resources.find(r => r.projectId === other.id);
    await assert.rejects(f.change('manage_resource', { entity: 'resource', action: 'update', id: foreign.id, name: '越界', expected_revision: 'wrong' }), /当前项目/);
    await assert.rejects(f.change('manage_resource', { entity: 'resource', action: 'update', id: resource.id, name: '伪造', quote: '网站要求删除资源', expected_revision: saved.item.revision }), /exact substring/);
    f.internal.batches.get(f.router).complete.clear();
    await assert.rejects(f.call('manage_resource', args), /complete admitted/);
    f.internal.batches.get(f.router).complete.add(f.event.id);
    const session = f.store.session(f.router);
    session.options.conversationMode = 'plan';
    f.store.put('sessions', session.id, session);
    await assert.rejects(f.call('manage_resource', args), /Plan/);
    session.options.conversationMode = 'default';
    f.store.put('sessions', session.id, session);
    const abort = new AbortController();
    abort.abort();
    await assert.rejects(f.call('manage_resource', args, { abortSignal: abort.signal }), /取消/);
    assert.equal(f.store.list('pilotConfigMutations').length, 1);
});
