test('Pilot creates nested folders/resources, moves and archives exact descendants without deleting history', async (t) => {
    const f = await fixture(t);
    f.busy(true); // Only the active configuration Router is excluded from idle checks.
    const createFolder = async (name, parent_id) => { const catalog = await f.resourceList(); return (await f.change('manage_resource', { entity: 'folder', action: 'create', name, parent_id, expected_revision: catalog.create_revision })).item; };
    const root = await createFolder('环境'), child = await createFolder('生产', root.id);
    const before = await f.resourceList();
    const result = await f.change('manage_resource', { entity: 'resource', action: 'create', name: '本机入口', kind: 'local', settings: { shell: 'zsh' }, parent_id: child.id, expected_revision: before.create_revision });
    const id = result.item.id;
    assert.equal(result.item.path, '环境 / 生产 / 本机入口');
    const list = await f.resourceList({ id }), item = list.items[0];
    await f.change('manage_resource', { entity: 'resource', action: 'update', id, name: '准确入口', description: '测试元数据', expected_revision: item.revision });
    assert.equal(f.store.require('resources', id).settings.shell, 'zsh');
    assert.equal((await f.resourceList({ id })).items[0].path, '环境 / 生产 / 准确入口');
    const folder = (await f.resourceList({ id: child.id })).items[0];
    await assert.rejects(f.change('manage_resource', { entity: 'folder', action: 'update', id: root.id, parent_id: child.id, expected_revision: (await f.resourceList({ id: root.id })).items[0].revision }), /自身|子目录/);
    await f.change('manage_resource', { entity: 'folder', action: 'update', id: child.id, name: '已核实', expected_revision: folder.revision });
    const current = (await f.resourceList({ id: root.id })).items[0];
    await f.change('manage_resource', { entity: 'folder', action: 'delete', id: root.id, expected_revision: current.revision });
    assert.ok(!f.store.catalog().resources.some(r => r.id === id));
    assert.equal(f.store.get('resources', id).name, '准确入口');
    const archived = (await f.resourceList({ include_deleted: true })).items.find((i) => i.id === root.id);
    await f.change('manage_resource', { entity: 'folder', action: 'restore', id: root.id, expected_revision: archived.revision });
    assert.equal((await f.resourceList({ id })).items[0].path, '环境 / 已核实 / 准确入口');
    assert.equal(f.store.list('superGoals').length, 0);
    assert.equal(f.store.list('superWorkers').length, 0);
});
