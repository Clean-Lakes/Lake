export type LakeAvatarFamily=typeof lakeAvatarGroups[number]['family'];
export type LakeAvatarName=typeof lakeAvatarGroups[number]['avatars'][number]['id'];
export type LakeAvatarDefinition={id:LakeAvatarName;name:string;family:LakeAvatarFamily;aliases?:readonly string[]};
export const lakeAvatarCatalog:readonly LakeAvatarDefinition[]=lakeAvatarGroups.flatMap(group=>group.avatars.map(avatar=>({...avatar,family:group.family})));
const definitions=new Map(lakeAvatarCatalog.map(avatar=>[avatar.id,avatar]));
export function lakeAvatarDefinition(id:LakeAvatarName){return definitions.get(id)!;}
export function isLakeAvatarName(id:string):id is LakeAvatarName{return definitions.has(id as LakeAvatarName);}
